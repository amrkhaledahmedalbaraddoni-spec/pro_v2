package com.red.server.groups

import org.springframework.data.annotation.Id
import org.springframework.data.mongodb.core.index.Indexed
import org.springframework.data.mongodb.core.mapping.Document
import org.springframework.data.mongodb.core.query.Criteria
import org.springframework.data.mongodb.core.query.Query
import org.springframework.data.mongodb.core.MongoTemplate
import org.springframework.stereotype.Service
import java.time.Instant
import java.time.temporal.ChronoUnit

/**
 * نموذج النسخ الاحتياطية
 */
@Document("group_backups")
data class GroupBackup(
    @Id val id: String = "",
    @Indexed val groupId: String = "",
    val backupName: String = "",
    val backupType: String = "", // FULL, MESSAGES_ONLY, METADATA_ONLY
    val format: String = "", // JSON, XML, CSV
    val size: Long = 0L,
    val messageCount: Long = 0L,
    val memberCount: Long = 0L,
    val createdBy: String = "",
    val createdAt: Instant = Instant.now(),
    val expiresAt: Instant? = null,
    val autoGenerated: Boolean = false,
    val notes: String? = null,
    val status: String = "COMPLETED" // PENDING, IN_PROGRESS, COMPLETED, FAILED
)

/**
 * جدول الاستعادة التلقائية
 */
@Document("group_backup_schedule")
data class GroupBackupSchedule(
    @Id val id: String = "",
    @Indexed val groupId: String = "",
    val enabled: Boolean = true,
    val frequency: String = "", // DAILY, WEEKLY, MONTHLY
    val time: String = "", // HH:mm
    val backupType: String = "", // FULL, MESSAGES_ONLY
    val format: String = "", // JSON, XML, CSV
    val retentionDays: Int = 30,
    val lastRun: Instant? = null,
    val nextRun: Instant? = null,
    val createdAt: Instant = Instant.now(),
    val updatedAt: Instant = Instant.now()
)

data class CreateGroupBackupRequest(
    val backupName: String? = null,
    val backupType: String = "FULL",
    val format: String = "JSON",
    val notes: String? = null
)

data class SetupBackupScheduleRequest(
    val enabled: Boolean = true,
    val frequency: String = "DAILY",
    val time: String = "02:00",
    val backupType: String = "FULL",
    val format: String = "JSON",
    val retentionDays: Int = 30
)

data class RestoreGroupBackupRequest(
    val backupId: String,
    val restoreFull: Boolean = true,
    val includeMessages: Boolean = true,
    val includeMembers: Boolean = true,
    val includeSettings: Boolean = true
)

data class GroupBackupResponse(
    val id: String,
    val groupId: String,
    val backupName: String,
    val backupType: String,
    val format: String,
    val size: Long,
    val messageCount: Long,
    val memberCount: Long,
    val createdAt: Instant,
    val expiresAt: Instant?,
    val status: String
)

data class GroupBackupScheduleResponse(
    val id: String,
    val groupId: String,
    val enabled: Boolean,
    val frequency: String,
    val time: String,
    val backupType: String,
    val format: String,
    val retentionDays: Int,
    val lastRun: Instant?,
    val nextRun: Instant?
)

/**
 * خدمة إدارة النسخ الاحتياطية والاستعادة
 */
@Service
class GroupBackupManager(private val mongo: MongoTemplate) {

    /**
     * إنشاء نسخة احتياطية يدوية
     */
    fun createBackup(
        groupId: String,
        actorId: String,
        request: CreateGroupBackupRequest
    ): GroupBackupResponse {
        val backupName = request.backupName ?: "Backup_${Instant.now().epochSecond}"
        val expiresAt = Instant.now().plus(90, ChronoUnit.DAYS)

        val backup = GroupBackup(
            id = "${groupId}:${System.currentTimeMillis()}",
            groupId = groupId,
            backupName = backupName,
            backupType = request.backupType,
            format = request.format,
            size = 0L, // سيتم حسابه من البيانات الفعلية
            messageCount = 0L, // سيتم حسابه من GroupMessageDocument
            memberCount = 0L, // سيتم حسابه من GroupMember
            createdBy = actorId,
            createdAt = Instant.now(),
            expiresAt = expiresAt,
            autoGenerated = false,
            notes = request.notes,
            status = "COMPLETED"
        )

        mongo.save(backup)
        return backup.toResponse()
    }

    /**
     * الحصول على قائمة النسخ الاحتياطية
     */
    fun listBackups(groupId: String, limit: Int = 50): List<GroupBackupResponse> {
        val now = Instant.now()
        return mongo.find(
            Query(Criteria.where("groupId").`is`(groupId)),
            GroupBackup::class.java
        ).filter { it.expiresAt == null || it.expiresAt.isAfter(now) }
            .sortedByDescending { it.createdAt }
            .take(limit)
            .map { it.toResponse() }
    }

    /**
     * حذف نسخة احتياطية
     */
    fun deleteBackup(groupId: String, backupId: String) {
        val backup = mongo.findById(backupId, GroupBackup::class.java)
            ?: throw NoSuchElementException("Backup not found")
        require(backup.groupId == groupId) { "Backup does not belong to this group" }

        mongo.remove(Query(Criteria.where("id").`is`(backupId)), GroupBackup::class.java)
    }

    /**
     * استعادة من نسخة احتياطية
     */
    fun restoreBackup(
        groupId: String,
        actorId: String,
        request: RestoreGroupBackupRequest
    ): Map<String, Any> {
        val backup = mongo.findById(request.backupId, GroupBackup::class.java)
            ?: throw NoSuchElementException("Backup not found")
        require(backup.groupId == groupId) { "Backup does not belong to this group" }

        // في تطبيق حقيقي، سيتم استعادة البيانات بناءً على نوع النسخة
        // هنا نسجل العملية فقط
        return mapOf(
            "groupId" to groupId,
            "backupId" to request.backupId,
            "status" to "RESTORE_INITIATED",
            "restoreFullData" to request.restoreFull,
            "includeMessages" to request.includeMessages,
            "includeMembers" to request.includeMembers,
            "includeSettings" to request.includeSettings,
            "initiatedAt" to Instant.now().toString()
        )
    }

    /**
     * إعداد جدول النسخ الاحتياطية التلقائية
     */
    fun setupBackupSchedule(
        groupId: String,
        actorId: String,
        request: SetupBackupScheduleRequest
    ): GroupBackupScheduleResponse {
        val id = "$groupId:schedule"
        val nextRun = calculateNextRun(request.frequency, request.time)

        val schedule = GroupBackupSchedule(
            id = id,
            groupId = groupId,
            enabled = request.enabled,
            frequency = request.frequency,
            time = request.time,
            backupType = request.backupType,
            format = request.format,
            retentionDays = request.retentionDays,
            nextRun = nextRun,
            createdAt = Instant.now(),
            updatedAt = Instant.now()
        )

        mongo.save(schedule)
        return schedule.toResponse()
    }

    /**
     * الحصول على جدول النسخ الاحتياطية
     */
    fun getBackupSchedule(groupId: String): GroupBackupScheduleResponse? {
        return mongo.findById("$groupId:schedule", GroupBackupSchedule::class.java)?.toResponse()
    }

    /**
     * تحديث جدول النسخ الاحتياطية
     */
    fun updateBackupSchedule(
        groupId: String,
        request: SetupBackupScheduleRequest
    ): GroupBackupScheduleResponse {
        return setupBackupSchedule(groupId, "system", request)
    }

    /**
     * تعطيل النسخ الاحتياطية التلقائية
     */
    fun disableBackupSchedule(groupId: String) {
        val schedule = mongo.findById("$groupId:schedule", GroupBackupSchedule::class.java)
        if (schedule != null) {
            mongo.save(schedule.copy(enabled = false, updatedAt = Instant.now()))
        }
    }

    /**
     * تنظيف النسخ الاحتياطية المنتهية الصلاحية
     */
    fun cleanExpiredBackups() {
        val now = Instant.now()
        mongo.remove(
            Query(Criteria.where("expiresAt").lte(now)),
            GroupBackup::class.java
        )
    }

    private fun calculateNextRun(frequency: String, time: String): Instant {
        val now = Instant.now()
        return when (frequency) {
            "DAILY" -> now.plus(1, ChronoUnit.DAYS)
            "WEEKLY" -> now.plus(7, ChronoUnit.DAYS)
            "MONTHLY" -> now.plus(30, ChronoUnit.DAYS)
            else -> now.plus(1, ChronoUnit.DAYS)
        }
    }

    private fun GroupBackup.toResponse() = GroupBackupResponse(
        id, groupId, backupName, backupType, format, size, messageCount, memberCount, createdAt, expiresAt, status
    )

    private fun GroupBackupSchedule.toResponse() = GroupBackupScheduleResponse(
        id, groupId, enabled, frequency, time, backupType, format, retentionDays, lastRun, nextRun
    )
}
